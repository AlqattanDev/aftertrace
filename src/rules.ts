/** The entire case is a pure value. Browser time, drawing, sound and storage live elsewhere. */
export type EntryId = 'window' | 'door' | 'terrace';
export type StashId = 'planter' | 'bench' | 'clock';
export type SpotId = EntryId | 'pedestal' | StashId;
export type Phase = 'entry' | 'take' | 'stash' | 'handoff' | 'investigate' | 'result';
export type Fabric = 'coral' | 'mint' | 'violet';
export type Tread = 'dots' | 'zigzag' | 'bars';
export type Charm = 'moon' | 'star' | 'leaf';
export type ClueId = 'tread' | 'fabric' | 'charm';
export type Profile = { fabric: Fabric; tread: Tread; charm: Charm };
export type Suspect = Profile & { id: string; name: string };
export type Relic = { id: string; name: string; color: string };
export type Clue = { id: ClueId; spot: SpotId; value: Fabric | Tread | Charm; label: string; detail: string };

export const ENTRIES: ReadonlyArray<{ id: EntryId; label: string }> = [
  { id: 'window', label: 'Window' }, { id: 'door', label: 'Door' }, { id: 'terrace', label: 'Terrace' },
];
export const STASHES: ReadonlyArray<{ id: StashId; label: string }> = [
  { id: 'planter', label: 'Planter' }, { id: 'bench', label: 'Bench' }, { id: 'clock', label: 'Clock' },
];
export const SPOTS: ReadonlyArray<{ id: SpotId; label: string }> = [...ENTRIES, { id: 'pedestal', label: 'Display' }, ...STASHES];
export const RELICS: ReadonlyArray<Relic> = [
  { id: 'moonstone', name: 'Pocket Moon', color: '#a9c8ff' },
  { id: 'sunbird', name: 'Golden Sunbird', color: '#ffd176' },
  { id: 'pear', name: 'Impossible Pear', color: '#bee29c' },
  { id: 'teapot', name: 'Cloud Teapot', color: '#f5adc2' },
  { id: 'comet', name: 'Little Comet', color: '#d0adff' },
  { id: 'shell', name: 'Whisper Shell', color: '#ffbb97' },
];
export const STAR_THRESHOLDS = { two: 1800, three: 2400 } as const;
export const SCORE_MAX = 3000;
export const HINT_COST = 150;
export const WRONG_COST = 200;

export type ScoreBreakdown = {
  score: number; stars: 1 | 2 | 3; elapsedSeconds: number;
  evidence: number; timing: number; speed: number; firstTry: number; penalties: number;
  wrongCount: number; hintCount: number;
};
export type CaseResult = ScoreBreakdown & { culpritId: string; relicId: string; title: string };
export type CaseState = {
  version: 2; id: string; seed: number; relic: Relic; phase: Phase;
  profile: Profile; culpritId: string; suspects: Suspect[];
  entry: EntryId | null; stash: StashId | null; timing: number[];
  /** These objects are deposited by heist actions, never generated by a search. */
  traces: Clue[];
  found: Clue[]; searched: SpotId[]; hinted: SpotId[]; hintSpot: SpotId | null;
  wrongAccusations: string[]; result: CaseResult | null;
};
export type ActionResult = { state: CaseState; ok: boolean; message: string; clue?: Clue; hint?: SpotId; correct?: boolean };

const FABRICS: Fabric[] = ['coral', 'mint', 'violet'];
const TREADS: Tread[] = ['dots', 'zigzag', 'bars'];
const CHARMS: Charm[] = ['moon', 'star', 'leaf'];
const PEOPLE = ['Pip Bellweather', 'Nori Thimble', 'Coco Bramble', 'Tavi Puddlewick', 'Lumi Button', 'Miro Dapple'];
const titleCase = (text: string) => text.charAt(0).toUpperCase() + text.slice(1);
const isEntry = (value: unknown): value is EntryId => ENTRIES.some(e => e.id === value);
const isStash = (value: unknown): value is StashId => STASHES.some(s => s.id === value);
const isSpot = (value: unknown): value is SpotId => SPOTS.some(s => s.id === value);
const quality = (value: number) => Number.isFinite(value) ? Math.max(0, Math.min(1, value)) : 0;
const no = (state: CaseState, message: string): ActionResult => ({ state, ok: false, message });
const yes = (state: CaseState, message: string): ActionResult => ({ state, ok: true, message });

function seedNumber(seed: number | string): number {
  if (typeof seed === 'number') return Number.isFinite(seed) ? Math.trunc(seed) >>> 0 : 0;
  let value = 2166136261;
  for (let i = 0; i < seed.length; i++) value = Math.imul(value ^ seed.charCodeAt(i), 16777619);
  return value >>> 0;
}
function random(seed: number): () => number {
  let value = seed;
  return () => {
    value = (value + 0x6d2b79f5) >>> 0;
    let t = Math.imul(value ^ (value >>> 15), 1 | value);
    t ^= t + Math.imul(t ^ (t >>> 7), 61 | t);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
function shuffle<T>(values: readonly T[], rng: () => number): T[] {
  const out = [...values];
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}
function different<T>(values: readonly T[], from: T, rng: () => number): T {
  const alternatives = values.filter(value => value !== from);
  return alternatives[Math.floor(rng() * alternatives.length)];
}

export function createCase(seed: number | string, relicIndex = 0): CaseState {
  const normalizedSeed = seedNumber(seed);
  const rng = random(normalizedSeed);
  const index = Number.isFinite(relicIndex) ? ((Math.trunc(relicIndex) % RELICS.length) + RELICS.length) % RELICS.length : 0;
  const profile: Profile = {
    fabric: FABRICS[Math.floor(rng() * FABRICS.length)],
    tread: TREADS[Math.floor(rng() * TREADS.length)],
    charm: CHARMS[Math.floor(rng() * CHARMS.length)],
  };
  const names = shuffle(PEOPLE, rng).slice(0, 3);
  const ids = shuffle(['guest-1', 'guest-2', 'guest-3'], rng);
  const culprit: Suspect = { id: ids[0], name: names[0], ...profile };
  const decoys: Suspect[] = names.slice(1).map((name, i) => ({ id: ids[i + 1], name, ...profile }));
  // Each decoy shares two real traits. Which traits rule them out changes each case.
  const differences = shuffle<ClueId>(['fabric', 'tread', 'charm'], rng);
  decoys.forEach((decoy, i) => {
    const trait = differences[i];
    if (trait === 'fabric') decoy.fabric = different(FABRICS, profile.fabric, rng);
    if (trait === 'tread') decoy.tread = different(TREADS, profile.tread, rng);
    if (trait === 'charm') decoy.charm = different(CHARMS, profile.charm, rng);
  });
  return {
    version: 2, id: `aftertrace-${normalizedSeed.toString(36)}-${index}`, seed: normalizedSeed,
    relic: { ...RELICS[index] }, phase: 'entry', profile, culpritId: culprit.id,
    suspects: shuffle([culprit, ...decoys], rng), entry: null, stash: null, timing: [],
    traces: [], found: [], searched: [], hinted: [], hintSpot: null, wrongAccusations: [], result: null,
  };
}

/** A normalized meter position: center is perfect; either edge scores zero. */
export function gradeTiming(cursor: number): number {
  if (!Number.isFinite(cursor)) return 0;
  return quality(1 - Math.abs(cursor - .5) * 2);
}

export function enterGallery(state: CaseState, entry: EntryId, timingQuality: number): ActionResult {
  if (state.phase !== 'entry' || !isEntry(entry)) return no(state, 'Choose an entrance first.');
  const clue: Clue = {
    id: 'tread', spot: entry, value: state.profile.tread, label: `${titleCase(state.profile.tread)} sole print`,
    detail: `A ${state.profile.tread} pattern, left where you came in.`,
  };
  return yes({ ...state, phase: 'take', entry, timing: [quality(timingQuality)], traces: [clue] }, 'You are in. A little trail follows.');
}
export function takeRelic(state: CaseState, timingQuality: number): ActionResult {
  if (state.phase !== 'take') return no(state, 'Reach the display first.');
  const clue: Clue = {
    id: 'fabric', spot: 'pedestal', value: state.profile.fabric, label: `${titleCase(state.profile.fabric)} thread`,
    detail: `A ${state.profile.fabric} thread caught on the display.`,
  };
  return yes({ ...state, phase: 'stash', timing: [...state.timing, quality(timingQuality)], traces: [...state.traces, clue] }, `${state.relic.name} is yours. Find a hiding place.`);
}
export function hideRelic(state: CaseState, stash: StashId, timingQuality: number): ActionResult {
  if (state.phase !== 'stash' || !isStash(stash)) return no(state, 'Take the treasure first.');
  const clue: Clue = {
    id: 'charm', spot: stash, value: state.profile.charm, label: `${titleCase(state.profile.charm)} charm`,
    detail: `Your ${state.profile.charm} charm fell beside the hidden ${state.relic.name}.`,
  };
  return yes({ ...state, phase: 'handoff', stash, timing: [...state.timing, quality(timingQuality)], traces: [...state.traces, clue] }, 'Treasure hidden. Time to change sides.');
}
export function beginInvestigation(state: CaseState): ActionResult {
  if (state.phase !== 'handoff') return no(state, 'Finish hiding the treasure first.');
  return yes({ ...state, phase: 'investigate' }, 'Follow your trail. Find three clues.');
}
export function inspectSpot(state: CaseState, spot: SpotId): ActionResult {
  if (state.phase !== 'investigate' || !isSpot(spot)) return no(state, 'Search the gallery as the detective.');
  if (state.searched.includes(spot)) return no(state, 'Already searched. Try another spot.');
  const trace = state.traces.find(clue => clue.spot === spot);
  const searched = [...state.searched, spot];
  if (!trace) return yes({ ...state, searched }, 'Nothing here. Follow the trail you left.');
  const clue = { ...trace };
  return {
    state: { ...state, searched, found: [...state.found, clue], hintSpot: state.hintSpot === spot ? null : state.hintSpot },
    ok: true, clue,
    message: clue.id === 'charm' ? `${state.relic.name} recovered! A ${clue.value} charm was beside it.` : clue.label + ' found.',
  };
}

export function requestHint(state: CaseState): ActionResult {
  if (state.phase !== 'investigate') return no(state, 'Hints are available while investigating.');
  if (state.hintSpot) return { ...no(state, 'Your next clue is already marked.'), hint: state.hintSpot };
  const trace = state.traces.find(clue => !state.found.some(found => found.id === clue.id));
  if (!trace) return no(state, 'All clues found. Compare the three guests.');
  const hinted = state.hinted.includes(trace.spot) ? state.hinted : [...state.hinted, trace.spot];
  return {
    state: { ...state, hinted, hintSpot: trace.spot }, ok: true, hint: trace.spot,
    message: `Look at the ${SPOTS.find(spot => spot.id === trace.spot)!.label.toLowerCase()}.`,
  };
}
export function matchingSuspects(state: CaseState): Suspect[] {
  return state.suspects.filter(suspect => state.found.every(clue => suspect[clue.id] === clue.value));
}
export function canAccuse(state: CaseState): boolean {
  return state.phase === 'investigate' && ['tread', 'fabric', 'charm'].every(id => state.found.some(clue => clue.id === id));
}

export type ScoreInput = { timing: readonly number[]; elapsedSeconds: number; evidenceCount: number; wrongCount: number; hintCount: number };
export function calculateScore(input: ScoreInput): ScoreBreakdown {
  // Invalid clocks never accidentally earn the maximum speed bonus.
  const elapsedSeconds = Number.isFinite(input.elapsedSeconds) && input.elapsedSeconds >= 0 ? Math.min(9999, input.elapsedSeconds) : 9999;
  const count = (value: number, cap: number) => Number.isFinite(value) ? Math.max(0, Math.min(cap, Math.floor(value))) : cap;
  const evidenceCount = Number.isFinite(input.evidenceCount) ? count(input.evidenceCount, 3) : 0;
  const wrongCount = count(input.wrongCount, 2), hintCount = count(input.hintCount, 3);
  const evidence = evidenceCount * 500;
  const timing = Math.round(input.timing.slice(0, 3).reduce((sum, value) => sum + quality(value), 0) * 200);
  // 45 s of grace leaves time to read, then the bonus tapers off by 3 minutes.
  const speed = Math.round(600 * quality(1 - Math.max(0, elapsedSeconds - 45) / 135));
  const firstTry = wrongCount === 0 ? 300 : 0;
  const penalties = hintCount * HINT_COST + wrongCount * WRONG_COST;
  const score = Math.max(0, Math.min(SCORE_MAX, evidence + timing + speed + firstTry - penalties));
  const stars: 1 | 2 | 3 = score >= STAR_THRESHOLDS.three ? 3 : score >= STAR_THRESHOLDS.two ? 2 : 1;
  return { score, stars, elapsedSeconds, evidence, timing, speed, firstTry, penalties, wrongCount, hintCount };
}

export function accuse(state: CaseState, suspectId: string, elapsedSeconds: number): ActionResult {
  if (!canAccuse(state)) return no(state, state.phase === 'result' ? 'Case already closed.' : 'Find all three clues before choosing a guest.');
  if (!state.suspects.some(suspect => suspect.id === suspectId)) return no(state, 'Choose one of the three guests.');
  if (state.wrongAccusations.includes(suspectId)) return no(state, 'That guest has already been cleared.');
  if (suspectId !== state.culpritId) {
    return { state: { ...state, wrongAccusations: [...state.wrongAccusations, suspectId] }, ok: true, correct: false, message: 'One detail does not fit. Check the clues and try again.' };
  }
  const score = calculateScore({ timing: state.timing, elapsedSeconds, evidenceCount: state.found.length, wrongCount: state.wrongAccusations.length, hintCount: state.hinted.length });
  const result: CaseResult = {
    ...score, culpritId: state.culpritId, relicId: state.relic.id,
    title: score.stars === 3 ? 'Brilliant detective' : score.stars === 2 ? 'Case cracked' : 'Mystery solved',
  };
  return { state: { ...state, phase: 'result', result }, ok: true, correct: true, message: `${state.relic.name} returned. Case closed!` };
}

/** Rebuild known fields and reject corrupt, old, or internally inconsistent saved cases. */
export function validateCase(value: unknown): CaseState | null {
  if (!value || typeof value !== 'object') return null;
  const saved = value as Record<string, unknown>;
  if (saved.version !== 2 || typeof saved.seed !== 'number' || !Number.isInteger(saved.seed) || saved.seed < 0 || saved.seed > 0xffffffff) return null;
  if (!saved.relic || typeof saved.relic !== 'object') return null;
  const relicIndex = RELICS.findIndex(relic => relic.id === (saved.relic as Record<string, unknown>).id);
  if (relicIndex < 0 || !Array.isArray(saved.timing) || saved.timing.length > 3 || !saved.timing.every(q => typeof q === 'number' && Number.isFinite(q) && q >= 0 && q <= 1)) return null;
  let state = createCase(saved.seed, relicIndex);
  const equal = (a: unknown, b: unknown) => JSON.stringify(a) === JSON.stringify(b);
  if (saved.id !== state.id || !equal(saved.profile, state.profile) || saved.culpritId !== state.culpritId || !equal(saved.suspects, state.suspects) || !equal(saved.relic, state.relic)) return null;
  const phases: Phase[] = ['entry', 'take', 'stash', 'handoff', 'investigate', 'result'];
  const phaseIndex = phases.indexOf(saved.phase as Phase);
  if (phaseIndex < 0 || saved.timing.length !== Math.min(3, phaseIndex)) return null;
  if (phaseIndex >= 1) {
    if (!isEntry(saved.entry)) return null;
    state = enterGallery(state, saved.entry, saved.timing[0]).state;
  } else if (saved.entry !== null) return null;
  if (phaseIndex >= 2) state = takeRelic(state, saved.timing[1]).state;
  if (phaseIndex >= 3) {
    if (!isStash(saved.stash)) return null;
    state = hideRelic(state, saved.stash, saved.timing[2]).state;
  } else if (saved.stash !== null) return null;
  if (!equal(saved.traces, state.traces)) return null;
  if (!Array.isArray(saved.searched) || saved.searched.length > SPOTS.length || new Set(saved.searched).size !== saved.searched.length || !saved.searched.every(isSpot)) return null;
  if (phaseIndex >= 4) {
    state = beginInvestigation(state).state;
    for (const spot of saved.searched) state = inspectSpot(state, spot).state;
  } else if (saved.searched.length !== 0) return null;
  if (!equal(saved.found, state.found)) return null;
  if (!Array.isArray(saved.hinted) || saved.hinted.length > 3 || new Set(saved.hinted).size !== saved.hinted.length || !saved.hinted.every(spot => state.traces.some(clue => clue.spot === spot))) return null;
  if (saved.hintSpot !== null && (!isSpot(saved.hintSpot) || !saved.hinted.includes(saved.hintSpot) || state.searched.includes(saved.hintSpot))) return null;
  if (!Array.isArray(saved.wrongAccusations) || saved.wrongAccusations.length > 2 || new Set(saved.wrongAccusations).size !== saved.wrongAccusations.length || !saved.wrongAccusations.every(id => typeof id === 'string' && id !== state.culpritId && state.suspects.some(suspect => suspect.id === id))) return null;
  if (phaseIndex < 4 && (saved.hinted.length || saved.hintSpot !== null || saved.wrongAccusations.length)) return null;
  if (saved.wrongAccusations.length && !canAccuse(state)) return null;
  state = { ...state, hinted: [...saved.hinted] as SpotId[], hintSpot: saved.hintSpot as SpotId | null, wrongAccusations: [...saved.wrongAccusations] as string[] };
  if (phaseIndex === 5) {
    if (!saved.result || typeof saved.result !== 'object' || !canAccuse(state)) return null;
    const elapsed = (saved.result as Record<string, unknown>).elapsedSeconds;
    if (typeof elapsed !== 'number' || !Number.isFinite(elapsed) || elapsed < 0 || elapsed > 9999) return null;
    state = accuse(state, state.culpritId, elapsed).state;
    if (!equal(saved.result, state.result)) return null;
  } else if (saved.result !== null) return null;
  return state;
}
